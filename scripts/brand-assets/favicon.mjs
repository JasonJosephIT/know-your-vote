// Builds the favicon set from the KYV acronym logo on a cream tile (founder
// pick, 2026-10-14): legible in light and dark browser tabs, where the bare
// logo loses its cream Y or its dark K and V.
//   node scripts/brand-assets/favicon.mjs
// Writes public/brand/site/favicon-{16,32,48}.png, favicon.ico (16/32/48),
// favicon.svg (a 128px raster inside an SVG: the source logo is 1.4MB) and
// src/app/favicon.ico.
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const CREAM = "#F5EBD8"; // brand-cream
const PAD = 0.08;
const RADIUS = 0.19; // radius.lg (12) on a 64 grid
const site = "public/brand/site";
const logo = readFileSync("public/brand/kyv-logo-acronym.svg");

async function icon(size) {
  const inner = Math.round(size * (1 - 2 * PAD));
  const art = await sharp(logo)
    .trim()
    .resize(inner, inner, { fit: "contain", background: "#0000" })
    .png()
    .toBuffer();
  const tile = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${Math.round(size * RADIUS)}" fill="${CREAM}"/></svg>`;
  return sharp(Buffer.from(tile))
    .composite([{ input: art, gravity: "center" }])
    .png()
    .toBuffer();
}

// ICO with PNG entries (supported by every browser that reads .ico).
function ico(pngs) {
  const head = Buffer.alloc(6 + 16 * pngs.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(pngs.length, 4);
  let offset = head.length;
  pngs.forEach(([size, png], i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size, e);
    head.writeUInt8(size, e + 1);
    head.writeUInt16LE(1, e + 4);
    head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(png.length, e + 8);
    head.writeUInt32LE(offset, e + 12);
    offset += png.length;
  });
  return Buffer.concat([head, ...pngs.map(([, png]) => png)]);
}

const pngs = [];
for (const size of [16, 32, 48]) {
  const png = await icon(size);
  writeFileSync(`${site}/favicon-${size}.png`, png);
  pngs.push([size, png]);
}
const icoFile = ico(pngs);
writeFileSync(`${site}/favicon.ico`, icoFile);
writeFileSync("src/app/favicon.ico", icoFile);

const big = (await icon(128)).toString("base64");
writeFileSync(
  `${site}/favicon.svg`,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="Know Your Vote"><!-- Generated by scripts/brand-assets/favicon.mjs: KYV acronym logo on a cream tile. --><image href="data:image/png;base64,${big}" width="64" height="64"/></svg>\n`
);
console.log("favicon set written");
