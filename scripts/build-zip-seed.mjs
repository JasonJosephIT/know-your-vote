/* Generates supabase/migrations/0003_zip_seed.sql from the Census 2020
   relationship files (ZCTA520 <-> CD119, ZCTA520 <-> County):

     https://www2.census.gov/geo/docs/maps-data/data/rel2020/cd-sld/tab20_cd11920_zcta520_natl.txt
     https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_county20_natl.txt

   A ZIP is included when its dominant county (largest land overlap) is one
   of the four covered metros. A ZIP is is_split=true when two or more FL
   congressional districts each cover >= 5% of its land area — those ZIPs
   get one row per qualifying district and the resolver must ask the voter
   to confirm rather than auto-picking (FR-001).

   Run: node scripts/build-zip-seed.mjs <zcta_cd.txt> <zcta_county.txt> */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const [cdFile, countyFile] = process.argv.slice(2);
if (!cdFile || !countyFile) {
  console.error("usage: node scripts/build-zip-seed.mjs <zcta_cd.txt> <zcta_county.txt>");
  process.exit(1);
}

const METROS = {
  "12086": { name: "Miami-Dade", metro: "miami" },
  "12011": { name: "Broward", metro: "fort_lauderdale" },
  "12057": { name: "Hillsborough", metro: "tampa" },
  "12095": { name: "Orange", metro: "orlando" },
};
const SPLIT_SHARE = 0.05;

function rows(file) {
  const text = readFileSync(file, "utf8").replace(/^﻿/, "");
  const lines = text.split("\n").filter(Boolean);
  const header = lines[0].split("|");
  return lines.slice(1).map((l) => {
    const parts = l.split("|");
    return Object.fromEntries(header.map((h, i) => [h.trim(), parts[i]]));
  });
}

/* Dominant county per ZCTA (nationwide, so border ZIPs resolve honestly). */
const countyByZcta = new Map();
for (const r of rows(countyFile)) {
  const zcta = r.GEOID_ZCTA5_20;
  const county = r.GEOID_COUNTY_20;
  if (!zcta || !county) continue;
  const land = Number(r.AREALAND_PART) || 0;
  const cur = countyByZcta.get(zcta);
  if (!cur || land > cur.land) countyByZcta.set(zcta, { county, land });
}

const covered = new Map();
for (const [zcta, { county }] of countyByZcta) {
  if (METROS[county]) covered.set(zcta, METROS[county]);
}

/* FL district overlaps for covered ZCTAs. */
const districtsByZcta = new Map();
for (const r of rows(cdFile)) {
  const cd = r.GEOID_CD119_20;
  const zcta = r.GEOID_ZCTA5_20;
  if (!cd || !zcta || !cd.startsWith("12") || !covered.has(zcta)) continue;
  const districtNum = Number(cd.slice(2));
  if (!Number.isFinite(districtNum) || districtNum === 0) continue;
  const land = Number(r.AREALAND_PART) || 0;
  const zctaLand = Number(r.AREALAND_ZCTA5_20) || 0;
  const list = districtsByZcta.get(zcta) ?? [];
  list.push({ district: `FL-${districtNum}`, land, zctaLand });
  districtsByZcta.set(zcta, list);
}

const values = [];
let splitCount = 0;
for (const [zcta, list] of [...districtsByZcta].sort()) {
  const { name, metro } = covered.get(zcta);
  const countyFips = [...Object.entries(METROS)].find(([, m]) => m.metro === metro)[0];
  const total = list[0]?.zctaLand || list.reduce((s, d) => s + d.land, 0) || 1;
  const dominant = list.reduce((a, b) => (b.land > a.land ? b : a));
  const qualifying = list.filter(
    (d) => d === dominant || d.land / total >= SPLIT_SHARE
  );
  const isSplit = qualifying.length > 1;
  if (isSplit) splitCount++;
  for (const d of qualifying) {
    values.push(
      `('${zcta}','${countyFips}','${name.replace(/'/g, "''")}','${d.district}','${metro}',${isSplit},true)`
    );
  }
}

const sql = `-- ZIP -> county/district seed for the four covered metros.
-- Generated by scripts/build-zip-seed.mjs from the Census 2020 ZCTA520/CD119
-- and ZCTA520/County relationship files. Split ZIPs (>=2 districts each
-- covering >=5% of land area) carry one row per district with is_split=true.

DELETE FROM zip_district;
INSERT INTO zip_district
  (zip5, county_fips, county_name, congressional_district, metro, is_split, in_coverage)
VALUES
${values.join(",\n")};
`;

const out = path.join(root, "supabase", "migrations", "0003_zip_seed.sql");
writeFileSync(out, sql);
console.log(
  `wrote ${out}: ${values.length} rows, ${districtsByZcta.size} ZIPs, ${splitCount} split`
);
