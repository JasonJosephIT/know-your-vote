/* Generates supabase/migrations/0008_election_seed.sql: statewide FL
   election_event rows for the 2026 primary + general.

   Dates are transcribed from the Florida Division of Elections —
   https://dos.fl.gov/elections/for-voters/election-dates/ (fetched
   2026-07-06). Do NOT edit dates here without re-checking that page.
   Every row ships with verified_by NULL: nothing sends until the founder
   re-checks each row against details_url and flips verified_by (plan F4).

   Run: node scripts/build-election-seed.mjs */

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SOURCE = "https://dos.fl.gov/elections/for-voters/election-dates/";

/* dos.fl.gov, "2026 Florida Election Dates":
     Primary — August 18, 2026; register/change party by July 20; request
     vote-by-mail ballot by August 6; early voting August 8–15.
     General — November 3, 2026; register by October 5; request vote-by-mail
     ballot by October 22; early voting October 24–31.
   Early-voting rows are the statewide mandatory window; counties may offer
   more days at their supervisor's discretion. */
const EVENTS = [
  ["primary_2026", "registration_deadline", "2026-07-20"],
  ["primary_2026", "vbm_request_deadline", "2026-08-06"],
  ["primary_2026", "early_voting_start", "2026-08-08"],
  ["primary_2026", "early_voting_end", "2026-08-15"],
  ["primary_2026", "election_day", "2026-08-18"],
  ["general_2026", "registration_deadline", "2026-10-05"],
  ["general_2026", "vbm_request_deadline", "2026-10-22"],
  ["general_2026", "early_voting_start", "2026-10-24"],
  ["general_2026", "early_voting_end", "2026-10-31"],
  ["general_2026", "election_day", "2026-11-03"],
];

const values = EVENTS.map(
  ([election, type, date]) =>
    `  ('${type}', '${election}', '${date}', '${SOURCE}')`
).join(",\n");

const sql = `-- Generated by scripts/build-election-seed.mjs — do not edit by hand.
-- Statewide FL 2026 election dates from ${SOURCE}
-- (fetched 2026-07-06). verified_by is NULL by design: founder task F4
-- verifies each row against the source before anything can send.
-- Idempotent: ON CONFLICT DO NOTHING against uq_election_event_scope.

INSERT INTO election_event (event_type, election, event_date, details_url) VALUES
${values}
ON CONFLICT DO NOTHING;
`;

const out = path.join(root, "supabase", "migrations", "0008_election_seed.sql");
writeFileSync(out, sql);
console.log(`wrote ${out} (${EVENTS.length} events)`);
